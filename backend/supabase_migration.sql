ALTER TABLE documents        ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_history     ENABLE ROW LEVEL SECURITY;
ALTER TABLE analytics_events ENABLE ROW LEVEL SECURITY;

-- Service-role bypass policies (the backend authenticates with service_role)
DROP POLICY IF EXISTS "service_role_documents" ON documents;
CREATE POLICY "service_role_documents" ON documents FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "service_role_chat_history" ON chat_history;
CREATE POLICY "service_role_chat_history" ON chat_history FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "service_role_analytics_events" ON analytics_events;
CREATE POLICY "service_role_analytics_events" ON analytics_events FOR ALL USING (true) WITH CHECK (true);


-- ═══════════════════════════════════════════════════════════════════════════════
-- PINECONE VECTOR METADATA REFERENCE
-- ═══════════════════════════════════════════════════════════════════════════════
-- Each vector stored in Pinecone carries the following metadata fields.
-- This is NOT a Supabase table — it documents the Pinecone metadata schema
-- so the relationship between PostgreSQL and Pinecone is explicit.
--
-- Pinecone Vector ID format:  {document_id}::chunk::{chunk_index}
--
-- Pinecone Vector Metadata:
-- ┌─────────────────┬─────────┬─────────────────────────────────────────────┐
-- │ Field           │ Type    │ Description                                 │
-- ├─────────────────┼─────────┼─────────────────────────────────────────────┤
-- │ document_id     │ string  │ FK → documents.id (UUID)                    │
-- │ document_name   │ string  │ Original filename                           │
-- │ page_number     │ int     │ Source page (null for non-PDF)               │
-- │ chunk_index     │ int     │ Zero-based chunk position in document       │
-- │ uploaded_at     │ string  │ ISO 8601 timestamp of ingestion             │
-- │ text            │ string  │ Full chunk text (for retrieval display)      │
-- └─────────────────┴─────────┴─────────────────────────────────────────────┘
--
-- Pinecone Index Configuration:
--   Name:      enterprise-rag
--   Dimension: 384
--   Metric:    cosine
--   Type:      Serverless (AWS us-east-1)
--
-- The document_id field in Pinecone metadata links back to documents.id,
-- enabling cascade deletes: when a document is removed, the backend
-- deletes Pinecone vectors filtered by document_id.


-- ═══════════════════════════════════════════════════════════════════════════════
-- VERIFICATION QUERY
-- ═══════════════════════════════════════════════════════════════════════════════
-- Run this after the migration to confirm all tables and indexes exist.

DO $$
DECLARE
    tbl TEXT;
    idx TEXT;
BEGIN
    -- Verify tables
    FOR tbl IN SELECT unnest(ARRAY['documents', 'chat_history', 'analytics_events'])
    LOOP
        IF NOT EXISTS (
            SELECT 1 FROM information_schema.tables
            WHERE table_schema = 'public' AND table_name = tbl
        ) THEN
            RAISE EXCEPTION 'Table "%" does not exist', tbl;
        END IF;
    END LOOP;

    -- Verify indexes
    FOR idx IN SELECT unnest(ARRAY[
        'idx_documents_status',
        'idx_documents_uploaded_at',
        'idx_chat_history_session',
        'idx_chat_history_role',
        'idx_analytics_event_type',
        'idx_analytics_created_at'
    ])
    LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_indexes
            WHERE schemaname = 'public' AND indexname = idx
        ) THEN
            RAISE EXCEPTION 'Index "%" does not exist', idx;
        END IF;
    END LOOP;

    RAISE NOTICE '✓ Migration verified — all 3 tables and 6 indexes exist';
END;
$$;
